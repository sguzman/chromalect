import assert from "node:assert/strict";
import fs from "node:fs";
const dir="data/semantic/cedict-crossref/";
const read=n=>JSON.parse(fs.readFileSync(dir+n+"-v0.1.json","utf8"));
const hints=read("tatoeba-icu-word-segmentation-index");
const source=read("tatoeba-word-surface-id-index");
const live=read("tatoeba-live-word-record-audit-summary");
const credits=read("tatoeba-word-candidate-attribution");
const hashes=read("tatoeba-word-sentence-text-fingerprints");
assert.equal(hints.schema,"chromalect.semantic.tatoeba-icu-word-segmentation-index.v0.1");
assert.equal(hints.status,"machine_token_boundary_hints_only_no_independent_linguistic_approval");
assert.equal(hints.source.corpusSnapshotSHA256,source.source.uncompressedTSVSha256);
assert.equal(hints.source.corpusSnapshotSHA256,credits.source.snapshotSHA256);
assert.equal(hints.source.sourceSentenceTextCopied,false);
assert.equal(hints.source.acquisitionArtifactId,12501948737);
assert.match(hints.source.acquiredReportSHA256,/^[a-f0-9]{64}$/);
assert.match(hints.source.acquisitionArtifactZipSha256,/^[a-f0-9]{64}$/);
assert.equal(hints.engine.algorithm,"Intl.Segmenter");
assert.equal(hints.engine.locale,"zh");
assert.equal(hints.engine.icu,"78.3");
assert.equal(hints.summary.sourceRecordsChecked,27);
assert.equal(hints.summary.sourceIntegrityMatches,27);
assert.equal(hints.summary.machineHints,27);
assert.equal(hints.summary.singleICUSegment,17);
assert.equal(hints.summary.multipleICUSegments,4);
assert.equal(hints.summary.cutsICUSegment,6);
for(const k of ["independentlyVerifiedWordBoundaries","independentlyVerifiedReadings","approvedLexicalSenses","quotationRightsCleared"])
 assert.equal(hints.summary[k],0);
const known=new Map(source.records.flatMap(r=>r.sentenceIds.map(id=>[id,r.leadId])));
const checked=new Map(live.records.map(r=>[r.sentenceId,r]));
const creditIDs=new Set(credits.records.map(r=>r.sentenceId));
const hashesIDs=new Set(hashes.records.map(r=>r.sentenceId));
const observed=new Set();
const counts={single_icu_segment:0,multiple_icu_segments:0,cuts_icu_segment:0};
for(const r of hints.records){
 assert.ok(!observed.has(r.sentenceId));observed.add(r.sentenceId);
 assert.equal(r.leadId,known.get(r.sentenceId));
 assert.ok(creditIDs.has(r.sentenceId));
 assert.ok(hashesIDs.has(r.sentenceId));
 assert.equal(checked.get(r.sentenceId)?.matchedPinnedSentenceTextSHA256,true);
 assert.equal(checked.get(r.sentenceId)?.reuseRightsAdjudicated,false);
 assert.ok(Number.isInteger(r.offsetUTF16)&&r.offsetUTF16>=0);
 assert.ok(Number.isInteger(r.lengthUTF16)&&r.lengthUTF16>=2);
 assert.ok(Object.hasOwn(counts,r.segmentationHint));
 counts[r.segmentationHint]++;
 assert.equal(r.independentWordBoundaryVerified,false);
 assert.equal(r.contextualReadingVerified,false);
 assert.equal(r.lexicalSenseApproved,false);
 assert.ok(!("sentenceText" in r));
 assert.ok(!("sourceText" in r));
}
assert.equal(observed.size,27);
assert.equal(counts.single_icu_segment,hints.summary.singleICUSegment);
assert.equal(counts.multiple_icu_segments,hints.summary.multipleICUSegments);
assert.equal(counts.cuts_icu_segment,hints.summary.cutsICUSegment);
console.log("Pinned 27 machine segmentation hints, 0 linguistic approvals.");
