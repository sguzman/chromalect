import assert from "node:assert/strict";
import fs from "node:fs";
const dir="data/semantic/cedict-crossref/";
const full=JSON.parse(fs.readFileSync(dir+"full-lexical-review-queue-v0.1.json","utf8"));
const strict=JSON.parse(fs.readFileSync(dir+"strict-gloss-index-v0.1.json","utf8"));
const flagged=JSON.parse(fs.readFileSync(dir+"sense-review-queue-v0.1.json","utf8"));
const ledger=JSON.parse(fs.readFileSync("data/semantic/mandarin-1000-v0.1.json","utf8"));
const blocks=full.source.dictionaryExcerptBlocks.map(name=>JSON.parse(fs.readFileSync(dir+name,"utf8")));
const dictionary=blocks.flatMap(x=>x.records);
assert.equal(full.schema,"chromalect.semantic.full-lexical-review-queue.v0.1");
assert.equal(full.status,"unreviewed_source_first_all_candidate_senses");
assert.equal(full.source.dataLicense,"CC BY-SA 4.0");
assert.equal(full.source.pinnedCCCEDICTCommit,"63c2569948629323b515833930fdd10f285401b6");
assert.equal(full.counts.total,897);
assert.equal(full.records.length,897);
assert.equal(dictionary.length,1000);
assert.equal(full.counts.strictWholeTermMatches,649);
assert.equal(full.counts.noWholeTermMatch,248);
assert.equal(full.counts.high,15);
assert.equal(full.counts.medium,11);
assert.equal(full.counts.unclassified,222);
assert.equal(full.counts.literalMatchUnverified,649);
assert.equal(full.counts.independentLexicalApproved,0);
assert.equal(full.counts.independentEmojiApproved,0);
assert.equal(full.counts.productionVerified,0);
assert.equal(flagged.records.length,248);
const flaggedMap=new Map(flagged.records.map(x=>[x.rank+"|"+x.selectedMeaning,x]));
const keys=new Set();
const cohorts={matched:0,flagged:0};
for(const [i,row] of full.records.entries()){
 const corresponding=strict.records[i];
 const canonical=ledger.characters[row.rank-1];
 const key=row.rank+"|"+row.selectedMeaning;
 assert.ok(!keys.has(key),"No repeated sense keys");
 keys.add(key);
 assert.equal(row.rank,corresponding.rank);
 assert.equal(row.character,corresponding.character);
 assert.equal(row.selectedMeaning,corresponding.selectedMeaning);
 assert.equal(row.character,canonical.character);
 const match=canonical.screening.candidates.find(x=>x.expression&&x.selectedMeaning===row.selectedMeaning);
 assert.ok(match,"Not a first-tranche emoji candidate");
 assert.equal(row.sourceGlossGroupIndex,match.sourceGroupIndex);
 assert.equal(row.referenceDefinition,canonical.source.groupCandidates[match.sourceGroupIndex]);
 const dict=dictionary[row.rank-1];
 assert.equal(dict.character,row.character);
 assert.equal(row.dictionaryExcerpt,dict.excerpt);
 assert.equal(row.dictionarySource,dict.sourcePath);
 assert.equal(row.dictionaryBlobSha,dict.sourceBlobSha);
 assert.deepEqual(row.dictionaryReadings,dict.readings);
 assert.deepEqual(row.matchingDictionaryReadings,corresponding.matchingReadings);
 assert.equal(row.strictWholeTermMatch,corresponding.wholeTermMatch);
 assert.equal(row.productionVerified,false);
 assert.equal(row.lexicalDecision,"pending");
 assert.equal(row.visualComprehensionDecision,"pending");
 assert.ok(!("emojiExpression" in row)&&!("emoji" in row),"Blind lexical queue cannot show pictograms");
 if(row.strictWholeTermMatch){
  cohorts.matched++;
  assert.equal(row.cohort,"literal_match_unverified");
  assert.equal(row.priority,"literal_match_unverified");
  assert.equal(row.previousDeskObservation,null);
  assert.equal(flaggedMap.has(key),false);
 }else{
  cohorts.flagged++;
  const older=flaggedMap.get(key);
  assert.ok(older);
  assert.equal(row.cohort,"no_whole_term_match");
  assert.equal(row.priority,older.priority);
  assert.equal(row.previousDeskObservation,older.deskAnalysis.observation);
 }
}
assert.deepEqual(cohorts,{matched:649,flagged:248});
console.log("All-sense lexical readiness: 897/897 source-aligned, 649 literal-match and 248 discrepant candidates; independent approvals 0.");
