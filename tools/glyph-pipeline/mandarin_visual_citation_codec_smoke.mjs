import assert from "node:assert/strict";
import fs from "node:fs";
import {constructVisualCitationDecoder,audit,visualSchema} from "./mandarin_visual_citation_codec.mjs";
const get=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const source=get("site/pronunciation-citations-0001-1000.json");
const palette=get("site/layers-v0.1.json");
const features=get("data/phonetics/mandarin-initial-feature-candidates-v0.1.json");
const symbols=get("data/phonetics/written-final-symbol-control-v0.1.json");
const expected=get("data/phonetics/mandarin-visual-citation-codec-audit-v0.1.json");
const decoder=constructVisualCitationDecoder(source,palette,features,symbols);
assert.deepEqual(audit(source,palette,features,symbols),expected);
let total=0;
for(const c of source.characters)for(const r of c.readings){
 const wire=JSON.parse(JSON.stringify(decoder.encode(r)));
 assert.equal(wire.schema,visualSchema);
 assert.deepEqual(decoder.decode(wire),r);
 assert.ok(wire.final.indices.length>=1);
 total++;
}
assert.equal(total,1171);
const good=decoder.encode(source.characters[0].readings[0]);
const clone=()=>structuredClone(good);
let wrong=clone();wrong.schema="unversioned";assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.verified=true;assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.final.indices=[9];assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.final.indices=[0,0,0,0,0];assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.final.indices=[3.5];assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.final.token="i";assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.tone.symbol="↗";assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.tone.token="5";assert.throws(()=>decoder.decode(wrong));
wrong=clone();wrong.initial.humanApproved=true;assert.throws(()=>decoder.decode(wrong));
assert.throws(()=>decoder.encode({...source.characters[0].readings[0],humanApproved:true}));
const changedSymbols=structuredClone(symbols);
changedSymbols.records[0].iconRegistryIndices=[2];
assert.throws(()=>constructVisualCitationDecoder(source,palette,features,changedSymbols));
const changedPalette=structuredClone(palette);
changedPalette.palette_domains.tone.symbols["1"]="unproven";
assert.throws(()=>constructVisualCitationDecoder(source,changedPalette,features,symbols));
assert.equal(expected.counts.independentMachineSerializationRoundTrips,1171);
assert.equal(expected.counts.independentHumanVisualDecodings,0);
assert.equal(expected.counts.educationalEffectMeasurements,0);
assert.equal(expected.counts.independentlyVerifiedPhonemicMappings,0);
console.log("1,171 visual code machine roundtrips; tampered symbols, extra claims, invalid tones and unobserved codes rejected.");
