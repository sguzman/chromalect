import assert from "node:assert/strict";
import fs from "node:fs";
import {createFeatureVisualGrammar,audit,schema} from "./zhao_li_visual_feature_grammar.mjs";
const get=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const source=get("data/phonetics/zhao-li-2009-34-unit-reference-model-v0.1.json");
const palette=get("site/layers-v0.1.json");
const evidence=get("data/phonetics/zhao-li-visual-feature-grammar-audit-v0.1.json");
const codec=createFeatureVisualGrammar(source,palette);
assert.deepEqual(audit(source,palette),evidence);
assert.equal(codec.sourceUnitCount,34);
assert.equal(codec.onsetCount,21);
assert.equal(codec.vowelCount,12);
assert.deepEqual(codec.codaTokens,["n","N"]);
assert.equal(codec.modelUnits.length,34);
const sample={onset:"P",vowels:["i","a","u"],coda:"N",tone:2};
const wire=JSON.parse(JSON.stringify(codec.encode(sample)));
assert.equal(wire.schema,schema);
assert.deepEqual(codec.decode(wire),sample);
assert.equal(wire.onset.segmentClass,"consonant");
assert.equal(wire.onset.voicingAspiration,"voiceless_aspirated");
assert.equal(wire.vowels[0].segmentClass,"vowel");
assert.equal(wire.coda.manner,"nasal");
assert.equal(wire.tone.symbol,"↗");
const serialized=JSON.stringify(wire);
for(const value of ["sourceToken","notation","workingIPACandidate","pinyinInitial",
 "writtenFinal","sourceSpelling"])assert.equal(serialized.includes('"'+value+'"'),false);
assert.equal(serialized.includes('"P"'),false);
const reject=(change)=>{
 const copy=structuredClone(wire);change(copy);
 assert.throws(()=>codec.decode(copy));
};
reject(w=>w.schema="unknown");
reject(w=>w.sourceModel="unversioned");
reject(w=>w.riskApproval=true);
reject(w=>w.vowels[0].originalSourceToken="i");
reject(w=>w.vowels[0].place="nonexistent");
reject(w=>w.vowels[0].height="none");
reject(w=>w.vowels[0].segmentClass="consonant");
reject(w=>w.onset.voicingAspiration="invented");
reject(w=>w.coda.place="labiodental");
reject(w=>w.vowels=[]);
reject(w=>w.vowels=["notEncoded"]);
reject(w=>w.vowels.push(...w.vowels));
reject(w=>w.tone.symbol="??");
reject(w=>w.tone.extra=true);
reject(w=>w.onset=w.coda); // velar nasal is not a permitted source onset
assert.throws(()=>codec.encode({onset:"N",vowels:["i"],coda:null,tone:1}));
assert.throws(()=>codec.encode({onset:"P",vowels:["i"],coda:"m",tone:1}));
assert.throws(()=>codec.encode({onset:"P",vowels:["i"],coda:null,tone:5}));
assert.throws(()=>codec.encode({onset:null,vowels:["a","i","a","u"],coda:null,tone:2}));
assert.throws(()=>codec.encode({onset:null,vowels:["u"],coda:null,tone:1,ipaApproved:true}));
const wrongSource=structuredClone(source);
wrongSource.summary.acceptedProjectPhonemeContrasts=1;
assert.throws(()=>createFeatureVisualGrammar(wrongSource,palette));
const collided=structuredClone(source);
collided.phonologicalUnits.find(x=>x.sourceToken==="a").articulatoryPlace="back";
assert.throws(()=>createFeatureVisualGrammar(collided,palette));
const tone=structuredClone(palette);
tone.palette_domains.tone.symbols["1"]="invented";
assert.throws(()=>createFeatureVisualGrammar(source,tone));
assert.equal(evidence.counts.unitIsolationMachineRoundTrips,34);
assert.equal(evidence.counts.modelSequenceDemonstrationRoundTrips,9);
assert.equal(evidence.counts.firstTrancheContextualIPARealizations,0);
assert.equal(evidence.counts.humanVisualSymbolDecodingResults,0);
console.log("34-unit visual grammar: source-model units encode to feature-only shapes and round-trip; CVVVCT invalids rejected, zero Pinyin-based phonetic approvals.");
