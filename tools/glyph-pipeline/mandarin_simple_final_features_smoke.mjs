import assert from "node:assert/strict";
import fs from "node:fs";
import {deriveSimpleFinals} from "./mandarin_simple_final_features.mjs";
const get=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const source=get("site/pronunciation-citations-0001-1000.json");
const layers=get("site/layers-v0.1.json");
const caution=get("data/phonetics/mandarin-final-spelling-context-gates-v0.1.json");
const d=get("data/phonetics/mandarin-simple-final-feature-candidates-v0.1.json");
assert.deepEqual(deriveSimpleFinals(source,layers,caution),d);
assert.equal(d.schema,"chromalect.phonetics.mandarin-simple-final-feature-candidates.v0.1");
assert.equal(d.status,"six_pedagogical_written_final_feature_hypotheses_not_ipa_or_context_approval");
assert.deepEqual(d.records.map(x=>x.token),["a","o","e","i","u","ü"]);
assert.deepEqual(d.records.map(x=>x.observedSourceCitationReadings),[72,16,45,168,128,3]);
assert.deepEqual(d.records.map(x=>x.sourceSpellingContextCautions),[0,16,0,63,33,0]);
assert.equal(d.summary.simpleFinalOccurrences,432);
assert.equal(d.summary.flaggedSimpleFinalOccurrences,112);
assert.equal(d.summary.unflaggedSimpleFinalOccurrences,320);
assert.equal(d.summary.uniqueWorkingFeatureTuples,6);
assert.equal(d.summary.independentIPAApprovalCount,0);
assert.equal(d.summary.humanVowelFeatureDecodingTrials,0);
assert.equal(d.summary.learningOutcomeEvidence,0);
assert.ok(d.records.every(x=>!x.acceptedAsIPAOrContextualPhone));
assert.equal(d.source.paletteChanged,false);
const corrupted=structuredClone(caution);
corrupted.summary.flaggedSourceReadings=212;
assert.throws(()=>deriveSimpleFinals(source,layers,corrupted));
const broken=structuredClone(layers);
delete broken.palette_domains.final.tokens["ü"];
assert.throws(()=>deriveSimpleFinals(source,broken,caution));
console.log("Six source-attested simple-final feature hypotheses remain unapproved and context-aware.");
